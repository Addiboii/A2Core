"""Improvised Damage rows for chain follow-ups whose SkillEffect.dat rows were not exported.

Why the rows are missing: tools/class_skills.py merges the chain-only skills (Skill.dat ChainSkillPrevSkillId: the combo
follow-ups of Winter's Shackles, Defiance, Overhead Slam, ...) from the bare Skill table, and that table carries only the group
ids of SkillEffectTimeDataList, not the SkillEffect.dat rows behind them. `class_skills.table_skills(path, effect_table)` now
resolves the groups when SkillEffect.dat is at hand (research/local/skill-tables-*/table-001.json) and the real Damage rows win.
Where the table is not at hand (the cloud VM, any machine without research/local) this module gives the follow-up a sensible
damage of OURS, scaled from its parent, and marks it:

  class-skills.json   skill['damage_source'] == 'override' (a real export replaces the rows; nothing marks real rows)
  skill-damage-overrides.json   the rule, parent, scale and rows of every improvised skill (the evidence)

Rules (a candidate is a chain-only Active class skill aimed at an enemy: MainTarget / MainSelf, no Damage row):
  follow-up   the parent has Damage rows: the same rows x FOLLOW_UP_SCALE. The real chain steps of the client data sit at
              1.11 - 1.17 of their parent (Keen Strike 4300 -> Rupture Strike 4900, Flame Arrow 6300 -> Burst 7025 -> Pyroclasm
              8200, Ice Chain 9250 -> Cold Wave 10300).
  ultimate    a 60 s+ cooldown or a parent without Damage rows (the Defiance follow-ups, 120 s, an area stun): one hit of
              ULTIMATE_SCALE x the strongest single row among the class's base (non-chain) skills.
The effect ids follow the client numbering (skill * 100 + group * 10 + n, tools/data/class-skills.json 1511000011), built on the
follow-up's family so the 0x3804 hit names a row the client knows.

    python tools/skill_damage_overrides.py           # writes tools/data/skill-damage-overrides.json and patches class-skills.json
    python tools/skill_damage_overrides.py --check   # exits 1 when either is out of date
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from data_json import write_data_json

ROOT = Path(__file__).resolve().parents[1]
CLASS_SKILLS = ROOT / 'tools/data/class-skills.json'
OUT = ROOT / 'tools/data/skill-damage-overrides.json'

FOLLOW_UP_SCALE = 1.15
ULTIMATE_SCALE = 1.5
ULTIMATE_COOLDOWN_MS = 60_000
CLASSES = {'11': 'Gladiator', '12': 'Templar', '13': 'Assassin', '14': 'Ranger', '15': 'Sorcerer', '16': 'Elementalist', '17': 'Cleric',
           '18': 'Chanter'}
ENEMY_TARGETS = ('MainTarget', 'MainSelf')
# Developer branch-test skills (Test Branch / Branch A / Branch B): not part of any class kit.
DEV_SKILLS = {11999001, 11999002, 11999003}
NOTE = ('Improvised Damage rows (OURS) for chain follow-ups whose SkillEffect.dat rows were not exported, scaled from the parent skill '
        '(generated by tools/skill_damage_overrides.py). `python tools/class_skills.py chains --effect-table <SkillEffect table-001.json>` '
        'replaces a skill as soon as its real rows are exported: tables win.')


def family(skill_id):
    return int(skill_id) // 10_000 * 10_000


def is_candidate(skill_id, skill):
    sid = int(skill_id)
    return (len(str(skill_id)) == 8 and str(skill_id)[:2] in CLASSES and sid not in DEV_SKILLS and skill.get('type') == 'Active'
            and int(skill.get('chain_prev') or 0) > 0 and skill.get('target') in ENEMY_TARGETS)


def has_real_damage(skill):
    return bool(skill.get('damage')) and skill.get('damage_source') != 'override'


def _scale_pair(pair, factor):
    return [None if v is None else max(1, round(v * factor)) for v in pair]


def _scale_values(values, factor):
    return {'flat': _scale_pair(values['flat'], factor), 'ratio': _scale_pair(values['ratio'], factor)}


def scaled_row(row, factor, effect_id):
    out = {'flat': _scale_pair(row['flat'], factor), 'ratio': _scale_pair(row['ratio'], factor), 'value4': row.get('value4'),
           'pvp': _scale_values(row['pvp'], factor) if row.get('pvp') else None, 'effect_id': effect_id}
    if row.get('hit_at_ms'):
        out['hit_at_ms'] = row['hit_at_ms']
    return out


def class_reference(skills, class_prefix):
    """The strongest single Damage row of the class's base skills (no chain parent, not a follow-up), or None."""
    best = None
    for skill_id, skill in skills.items():
        if (str(skill_id)[:2] != class_prefix or len(str(skill_id)) != 8 or skill.get('type') != 'Active' or skill.get('chain_prev')
                or not has_real_damage(skill)):
            continue
        for row in skill['damage']:
            if best is None or (row['ratio'][0] or 0) > (best['ratio'][0] or 0):
                best = row
    return best


def _depth(skills, skill_id):
    depth = 0
    while skills.get(str(skill_id), {}).get('chain_prev') and depth < 16:
        skill_id = str(skills[str(skill_id)]['chain_prev'])
        depth += 1
    return depth


def improvise(doc):
    """{skill id: override entry} for every candidate of the class-skills document without real Damage rows."""
    skills = doc['skills']
    work = {k: {**v, 'damage': v['damage'] if has_real_damage(v) else []} for k, v in skills.items()}
    found = {}
    for skill_id in sorted((k for k, v in work.items() if is_candidate(k, v) and not v['damage']), key=lambda k: (_depth(work, k), int(k))):
        skill = work[skill_id]
        parent_id = str(skill['chain_prev'])
        parent_rows = work.get(parent_id, {}).get('damage') or []
        base = family(skill_id) * 100
        if parent_rows and skill.get('cooldown_ms', 0) < ULTIMATE_COOLDOWN_MS:
            rule, factor = 'follow-up', FOLLOW_UP_SCALE
            rows = [scaled_row(r, factor, base + int(r['effect_id']) % 100) for r in parent_rows]
            evidence = (f'Chain follow-up of {parent_id} ({work[parent_id].get("name")}): its {len(parent_rows)} Damage row(s) x {factor}, '
                        f'the step-up of the real chain steps in the client data (1.11 - 1.17).')
        else:
            reference = class_reference(work, str(skill_id)[:2])
            if reference is None:
                continue
            rule, factor = 'ultimate', ULTIMATE_SCALE
            rows = [scaled_row(reference, factor, base + 11)]
            evidence = (f'{skill["cooldown_ms"] // 1000} s follow-up of {parent_id} ({work[parent_id].get("name")}, no Damage rows of its own): '
                        f'one hit of {factor} x the strongest base skill row of the {CLASSES[str(skill_id)[:2]]}.')
        skill['damage'] = rows
        found[skill_id] = {'name': skill.get('name'), 'parent': int(parent_id), 'rule': rule, 'scale': factor, 'evidence': evidence, 'rows': rows}
    return found


def apply(doc, overrides):
    """Write the override rows into the class-skills document; a skill with real rows keeps them. Returns the ids changed."""
    applied = []
    for skill_id, entry in overrides.get('skills', {}).items():
        target = doc['skills'].get(skill_id)
        if target is None or has_real_damage(target):
            continue
        target['damage'] = entry['rows']
        target['damage_source'] = 'override'
        applied.append(skill_id)
    return applied


def clear(doc):
    """Drop every previously improvised row, so a re-run scales from the current parents and real exports show through."""
    for skill in doc['skills'].values():
        if skill.get('damage_source') == 'override':
            skill['damage'] = []
            del skill['damage_source']


def patch(doc):
    """Improvise the missing rows of `doc` in place; returns the override document."""
    clear(doc)
    overrides = {'note': NOTE, 'follow_up_scale': FOLLOW_UP_SCALE, 'ultimate_scale': ULTIMATE_SCALE,
                 'ultimate_cooldown_ms': ULTIMATE_COOLDOWN_MS, 'skills': improvise(doc)}
    applied = apply(doc, overrides)
    if applied and isinstance(doc.get('evidence'), dict):
        doc['evidence']['damage_source'] = ('chain follow-ups without exported SkillEffect rows carry improvised Damage rows scaled from '
                                            'their parent (damage_source: override, tools/data/skill-damage-overrides.json)')
    return overrides


def render(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + '\n'


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    doc = json.loads(CLASS_SKILLS.read_text(encoding='utf-8'))
    overrides = patch(doc)
    if '--check' in args:
        current = json.loads(CLASS_SKILLS.read_text(encoding='utf-8'))
        stale_rows = any(current['skills'][k].get('damage') != v['damage'] for k, v in doc['skills'].items())
        return 0 if OUT.exists() and OUT.read_text(encoding='utf-8') == render(overrides) and not stale_rows else 1
    OUT.write_text(render(overrides), encoding='utf-8')
    write_data_json(CLASS_SKILLS, doc)
    print(f'{OUT}: {len(overrides["skills"])} follow-up skills got improvised Damage rows')
    return 0


if __name__ == '__main__':
    sys.exit(main())
