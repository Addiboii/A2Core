def build():
    names = {int(k) // 10_000: v['name'] for k, v in json.loads(CLASS_SKILLS.read_text(encoding='utf-8'))['skills'].items()}
    skills = {}
    for skill, entry in sorted(SKILLS.items()):
        name = names.get(skill // 10_000)
        if name is None:
            raise SystemExit(f'skill {skill} is not a class skill family')
        skills[str(skill)] = {'name': name, 'family': True, **entry}
    abnormals = {str(a): {'effects': rows, 'evidence': evidence} for a, (rows, evidence) in sorted(ABNORMALS.items())}
    return {'note': NOTE, 'skills': skills, 'abnormals': abnormals}


def render(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + '\n'


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    text = render(build())
    if '--check' in args:
        return 0 if OUT.exists() and OUT.read_text(encoding='utf-8') == text else 1
    OUT.write_text(text, encoding='utf-8')
    print(f'{OUT}: {len(SKILLS)} skills, {len(ABNORMALS)} abnormals')
    return 0


if __name__ == '__main__':
    sys.exit(main())
