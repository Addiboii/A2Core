"""Improvised effect rows for class skills whose client SkillEffect / SkillAbnormalEffect rows are not at hand.

The committed skill-areas.json carries damage and the debuff abnormals of every class skill, but not the other SkillEffect rows
(heals, dispels, pulls...) nor what each abnormal does (SkillAbnormalEffect): the research tables are not on every machine.
This module is the one place where those gaps are filled with sensible, clearly marked values, written to
tools/data/skill-effect-overrides.json and applied to skill-areas.json by `python tools/skill_areas.py patch`.

The rows use the client's own names (usmap): ESkillEffectType for a skill row, EAbnormalEffectType for an abnormal row, with these
value layouts (the layouts of the item rows HpHeal_Item / Hot_Item / HotRatio_Item / Dot_TargetMaxHP, which are in the client data):

  skill rows
    HpHeal / MpHeal / SpHeal [min, max]            flat points
    HpHealRatio / MpHealRatio / SpHealRatio [min, max]   1/10000 of the target's maximum
    Dispel_Cc, Dispel_True [DeBuff|Buff]           cleanse: crowd control / every debuff (or buff) of the friendly targets
    Dispel [count]                                 purge: buffs of an enemy
    Pull [distance cm]                             pulls the enemy towards the caster (Abnormal_Move_Start_NT, move type Pull)
    IncreaseCooltime / DecreaseCooltime [ms, skill group (0: every)]
    MPBurn [min, max], AggroTransfer [permille]
  abnormal rows
    Stun, Hold, Sleep, Frozen, Knockdown           hold the target
    Aerial [height cm, ms]                         airborne: lifted for the abnormal's duration (held)
    Knockback [distance cm, ms]                    pushed away from the caster (Abnormal_Move_Start_NT, move type Knockback)
    Slow [1/10000 of the move speed], Snare        slowed / rooted (movement only)
    Silence, Taunt                                 no skills / forced onto the taunter
    Dot_TargetMaxHP [interval ms, 1/10000 of max HP in total, cap]
    Hot_Ratio [interval ms, ratio min, ratio max, cap]   (HotRatio_Item layout), StatChange [stat, value]
    ImmuneAbnormal [_, _, _, _, _, effect types, category]   (the layout of the item rows)

Every value is IMPROVISED unless the client data names it; `evidence` says why the row was chosen. A real export of the tables
replaces an entry (tables win), so none of this survives `python tools/skill_areas.py build` where the tables exist.
"""

