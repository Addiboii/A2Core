#!/usr/bin/env python3
"""Writes server/Aion.Protocol/Native/EResult.cs: the client's EResult codes from the usmap (one const per name).

The client picks its message from a reply's result, so replies must use these codes, not small numbers of our own:
2 is kFail_ContentsBan and 3 kFail_AccountBan ("unavailable due to account restrictions").
    python3 tools/gen_eresult.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from packet_schema import PacketSchema  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "server/Aion.Protocol/Native/EResult.cs"


def main() -> int:
    values = PacketSchema().parser.enums["EResult"]
    seen = {}
    lines = []
    for value, name in sorted(values.items()):
        ident = re.sub(r"\W", "_", name[1:] if name.startswith("k") else name)
        ident = ident[:1].upper() + ident[1:]
        if ident in seen or not ident:   # the usmap has a few case variants (kitem_ / kItem_)
            ident = f"{ident}_{value}"
        seen[ident] = value
        lines.append(f"    public const int {ident} = {value};")
    OUT.write_text(
        "// Generated by tools/gen_eresult.py from the usmap enum EResult. Do not edit.\n"
        "namespace Aion.Protocol.Native;\n\n"
        "/// <summary>The client's result codes: a reply's result picks the message the client shows.</summary>\n"
        "public static class EResult\n{\n" + "\n".join(lines) + "\n}\n")
    print(f"{len(lines)} codes -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
