"""List every CANDIDATE and OURS marker in the server code as a Markdown work list.

    python tools/list_markers.py > docs/GUESSES.md

CANDIDATE values are inferred and wait for a recording or a live test; OURS values are our own choice where the
client gives nothing. One line per marker: the file and line, then the comment's text. Standard library only.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDERS = ('server/Aion.World', 'server/Aion.Protocol', 'server/Aion.Host', 'server/Aion.Core', 'server/Aion.Infrastructure')
MARKER = re.compile(r'\b(CANDIDATE|OURS)\b')


def text_of(line):
    """The comment on a source line, without the comment signs and XML doc tags."""
    comment = line.split('//', 1)[1] if '//' in line else line
    comment = re.sub(r'</?(summary|param|see|paramref|c|remarks|returns)[^>]*>', '', comment.lstrip('/'))
    return ' '.join(comment.replace('&lt;', '<').replace('&gt;', '>').split())


def markers(root=ROOT):
    found = {'CANDIDATE': [], 'OURS': []}
    for folder in FOLDERS:
        for path in sorted((root / folder).rglob('*.cs')):
            if {'bin', 'obj'} & set(path.parts):
                continue
            for number, line in enumerate(path.read_text(encoding='utf-8', errors='replace').splitlines(), 1):
                for kind in dict.fromkeys(MARKER.findall(line)):
                    found[kind].append((path.relative_to(root).as_posix(), number, text_of(line)))
    return found


def markdown(found):
    out = ['# Values that are still guesses', '',
           'Generated by `python tools/list_markers.py`. Do not edit by hand: fix the value in the code, change its marker,',
           'and run the tool again.', '',
           f'- **CANDIDATE** ({len(found["CANDIDATE"])}): inferred, waiting for a recording of the official server or a live test.',
           f'- **OURS** ({len(found["OURS"])}): our own choice where the client gives nothing. Many are server rules that can',
           '  stay; the ones about timings, amounts and formulas are worth confirming.', '']
    for kind in ('CANDIDATE', 'OURS'):
        out += [f'## {kind}', '']
        current = None
        for path, number, text in found[kind]:
            if path != current:
                out += ['' if current else None, f'### `{path}`', ''] if current else [f'### `{path}`', '']
                current = path
            out.append(f'- line {number}: {text[:220]}')
        out.append('')
    return '\n'.join(line for line in out if line is not None)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', newline='\n')
    sys.stdout.write(markdown(markers()) + '\n')
