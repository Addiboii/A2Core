"""Boss / dungeon drop rates as XML, from the aion2hub.com public drop-rates page (downloaded once by the user, parsed to JSON).

Input: ~/reference/aion2hub-drop-rates.json {source, rows: [{item_id, name, grade, category, source, rate}]}. The rates are
percentages per kill or clear from the Launch Scale Test client (2026-09-19), UNOFFICIAL; "Ceiling" marks a guaranteed pity
reward (not rolled). Output: gamedata/drops/aion2hub.xml, one <source> per source with the dungeon it applies to (its final
boss, MapEventTables CubeBoss) or apply="none" when no NPC can be matched reliably (Field Boss, Field Elite, events). Staff
may edit the file; the server reads it at start-up (DropDB).

    python3 tools/drop_xml.py [path/to/aion2hub-drop-rates.json]
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = Path.home() / 'reference/aion2hub-drop-rates.json'
OUT = ROOT / 'gamedata/drops/aion2hub.xml'

# aion2hub source name -> dungeon id (map-events.json dungeons: Party dungeons, their final boss gets the drops).
DUNGEONS = {
    'Krao Cave (Easy)': 600002, 'Krao Cave (Normal)': 600001,
    'Urugugu Canyon (Easy)': 600011, 'Urugugu Canyon (Normal)': 600012,
    'Fire Temple (Easy)': 600021, 'Fire Temple (Normal)': 600022,
    'Draupnir (Easy)': 600031, 'Draupnir (Normal)': 600032,
    'Vakron Sky Island (Easy)': 600071, 'Vakron Sky Island (Normal)': 600072,
    'Ferocious Horn Den (Easy)': 600091, 'Ferocious Horn Den (Normal)': 600092,
}


def rate(text):
    """'25%' -> 25.0; 'Ceiling' and the rest -> None (recorded, not rolled)."""
    text = str(text).strip()
    if text.endswith('%'):
        try:
            return float(text[:-1])
        except ValueError:
            return None
    return None


def main(argv):
    source_file = Path(argv[0]) if argv else DEFAULT
    data = json.loads(source_file.read_text(encoding='utf-8'))
    rows = [r for r in data['rows'] if r.get('source') and r['source'] != 'name' and r.get('item_id')]
    sources = {}
    for row in rows:
        sources.setdefault(row['source'], []).append(row)
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- Generated by tools/drop_xml.py from aion2hub.com drop rates (UNOFFICIAL, Launch Scale Test client 2026-09-19).',
           '     rate: percent per kill/clear; pity="true": a guaranteed ceiling reward (not rolled). apply: dungeon = its final',
           '     boss drops these on the ground for the killer, on top of the client reward tables; none = not matched to an NPC. -->',
           '<drops origin="aion2hub.com/database/drop-rates">']
    for name in sorted(sources):
        dungeon = DUNGEONS.get(name)
        apply = f'dungeon="{dungeon}"' if dungeon else 'apply="none"'
        out.append(f'\t<source name={quoteattr(name)} {apply}>')
        for row in sorted(sources[name], key=lambda r: (r['item_id'], str(r['rate']))):
            r = rate(row['rate'])
            attrs = f'rate="{r:g}"' if r is not None else f'pity="true" note={quoteattr(str(row["rate"]))}'
            out.append(f'\t\t<drop item="{int(row["item_id"])}" {attrs}/><!-- {escape(row.get("name") or "")} -->')
        out.append('\t</source>')
    out.append('</drops>\n')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(out), encoding='utf-8')
    print(f'{len(sources)} sources, {len(rows)} drops -> {OUT.relative_to(ROOT)} ({sum(1 for s in sources if s in DUNGEONS)} applied to dungeons)')


if __name__ == '__main__':
    main(sys.argv[1:])
