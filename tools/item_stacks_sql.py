"""Writes database/migrations/034_item_stacks.sql: item stack limits from Item.dat and a stacking game.grant_item.

Item.dat (research/local/quest-tables/table-016.json) MaxStackCount: Usable and Misc items carry their stack size
(999, 1000, 10000, 9999999 ...), Currency rows have 0 (no limit), Equip rows 0 too (never stack: one row per item).
The migration keeps the limits in game.item_stacks, replaces game.grant_item so a grant tops up an existing plain bag
stack of the same template (no upgrades, no rolled stats) before opening new rows, and merges the stacks characters
already hold (the first version of grant_item opened a row per grant: every gather and every kina reward sat alone).

    python tools/item_stacks_sql.py write                                      # 034 (first version only)
    python tools/item_stacks_sql.py update database/migrations/071_item_stacks_26262663.sql

034 is applied on every server and checksummed, so a newer client build does not rewrite it: `update` writes a new
migration with the stack limits that are new or changed against 034 and the earlier update migrations
(*_item_stacks_*.sql). Templates the newer build dropped keep their row (items of the old catalogue build may remain).
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ITEMS = ROOT / 'research/local/quest-tables/table-016.json'
OUT = ROOT / 'database/migrations/034_item_stacks.sql'

HEADER = """-- Item stacks (generated by tools/item_stacks_sql.py from Item.dat MaxStackCount; do not edit by hand).
-- Usable and Misc items stack to their limit; Currency has none; Equip never stacks. game.grant_item tops up an
-- existing plain bag stack (same build and template, no upgrades or rolled stats) before it opens new rows, and the
-- stacks characters already hold are merged once.
CREATE TABLE game.item_stacks (
    template_id integer PRIMARY KEY,
    max_stack integer NOT NULL CHECK (max_stack > 1)
);
"""

FUNCTION = """
-- Several grants may land in one stack now: the grant record's instance id is no longer unique (it still references the stack).
ALTER TABLE game.item_grants DROP CONSTRAINT IF EXISTS item_grants_instance_id_key;

CREATE OR REPLACE FUNCTION game.item_stack_max(p_build text, p_template integer) RETURNS integer
LANGUAGE sql STABLE AS $$
    SELECT CASE
        WHEN (SELECT definition->'facts'->>'ItemType' FROM catalog.items WHERE build_id = p_build AND template_id = p_template) = 'EItemType::Currency' THEN 0
        WHEN (SELECT definition->'facts'->>'ItemType' FROM catalog.items WHERE build_id = p_build AND template_id = p_template) = 'EItemType::Equip' THEN 1
        ELSE COALESCE((SELECT max_stack FROM game.item_stacks WHERE template_id = p_template), 1)
    END
$$;

CREATE OR REPLACE FUNCTION game.grant_item(p_character uuid, p_build text, p_template integer,
                                          p_quantity bigint, p_request uuid) RETURNS uuid
LANGUAGE plpgsql AS $$
DECLARE
    item_id uuid := gen_random_uuid();
    first_id uuid;
    args jsonb := jsonb_build_object('character',p_character,'build',p_build,'template',p_template,'quantity',p_quantity);
    previous game.item_grants%ROWTYPE;
    max_stack integer;
    remaining bigint := p_quantity;
    room bigint;
    stack record;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION 'quantity must be positive';
    END IF;
    INSERT INTO game.item_grants VALUES(p_request,args,item_id) ON CONFLICT DO NOTHING;
    IF NOT FOUND THEN
        SELECT * INTO previous FROM game.item_grants WHERE request_id=p_request;
        IF previous.arguments IS DISTINCT FROM args THEN
            RAISE EXCEPTION 'idempotency key reused with different arguments';
        END IF;
        RETURN previous.instance_id;
    END IF;
    max_stack := game.item_stack_max(p_build, p_template);
    IF max_stack <> 1 THEN
        -- Top up the existing plain bag stacks, fullest first.
        FOR stack IN SELECT instance_id, quantity FROM game.item_instances
                     WHERE character_id = p_character AND build_id = p_build AND template_id = p_template AND location = 'bag'
                       AND upgrades = '{}'::jsonb AND rolled_stats = '{}'::jsonb AND (max_stack = 0 OR quantity < max_stack)
                     ORDER BY quantity DESC, created_at FOR UPDATE
        LOOP
            EXIT WHEN remaining <= 0;
            room := CASE WHEN max_stack = 0 THEN remaining ELSE LEAST(remaining, max_stack - stack.quantity) END;
            UPDATE game.item_instances SET quantity = quantity + room, revision = revision + 1 WHERE instance_id = stack.instance_id;
            first_id := COALESCE(first_id, stack.instance_id);
            remaining := remaining - room;
        END LOOP;
    END IF;
    -- New rows for what is left, a full stack per row.
    WHILE remaining > 0 LOOP
        room := CASE WHEN max_stack = 0 THEN remaining ELSE LEAST(remaining, max_stack) END;
        INSERT INTO game.item_instances(instance_id,character_id,build_id,template_id,quantity)
            VALUES(CASE WHEN first_id IS NULL THEN item_id ELSE gen_random_uuid() END,p_character,p_build,p_template,room);
        first_id := COALESCE(first_id, item_id);
        remaining := remaining - room;
    END LOOP;
    -- The grant record points at the stack the grant landed in (several requests may now share one stack).
    IF first_id <> item_id THEN
        UPDATE game.item_grants SET instance_id = first_id WHERE request_id = p_request;
    END IF;
    INSERT INTO audit.events(action,character_id,details)
        VALUES('item_granted',p_character,jsonb_build_object('request',p_request,'instance',first_id,'template',p_template,'quantity',p_quantity));
    RETURN first_id;
END $$;

-- Merge the plain bag stacks characters already hold (one row per grant until now).
DO $merge$
DECLARE
    grp record;
    row record;
    keeper uuid;
    keeper_qty bigint;
    max_stack integer;
BEGIN
    FOR grp IN SELECT character_id, build_id, template_id FROM game.item_instances
               WHERE location = 'bag' AND upgrades = '{}'::jsonb AND rolled_stats = '{}'::jsonb
               GROUP BY character_id, build_id, template_id HAVING count(*) > 1
    LOOP
        max_stack := game.item_stack_max(grp.build_id, grp.template_id);
        CONTINUE WHEN max_stack = 1;
        keeper := NULL;
        FOR row IN SELECT instance_id, quantity FROM game.item_instances
                   WHERE character_id = grp.character_id AND build_id = grp.build_id AND template_id = grp.template_id
                     AND location = 'bag' AND upgrades = '{}'::jsonb AND rolled_stats = '{}'::jsonb
                   ORDER BY created_at, instance_id FOR UPDATE
        LOOP
            IF keeper IS NULL OR (max_stack <> 0 AND keeper_qty >= max_stack) THEN
                keeper := row.instance_id;
                keeper_qty := row.quantity;
                CONTINUE;
            END IF;
            IF max_stack = 0 OR keeper_qty + row.quantity <= max_stack THEN
                UPDATE game.item_instances SET quantity = quantity + row.quantity, revision = revision + 1 WHERE instance_id = keeper;
                DELETE FROM game.item_instances WHERE instance_id = row.instance_id;
                keeper_qty := keeper_qty + row.quantity;
            ELSE
                UPDATE game.item_instances SET quantity = max_stack, revision = revision + 1 WHERE instance_id = keeper;
                UPDATE game.item_instances SET quantity = quantity - (max_stack - keeper_qty), revision = revision + 1 WHERE instance_id = row.instance_id;
                keeper := row.instance_id;
                keeper_qty := row.quantity - (max_stack - keeper_qty);
            END IF;
        END LOOP;
    END LOOP;
END $merge$;

GRANT SELECT ON game.item_stacks TO aion_app;
GRANT EXECUTE ON FUNCTION game.item_stack_max(text,integer) TO aion_app;
"""


def stacks(items=ITEMS):
    rows = json.loads(Path(items).read_text(encoding='utf-8'))['Properties']['Data']
    return sorted((row['ID']['Value'], int(row['MaxStackCount'])) for row in rows
                  if isinstance(row.get('ID'), dict) and int(row.get('MaxStackCount') or 0) > 1
                  and str(row.get('ItemType', '')).split('::')[-1] in ('Usable', 'Misc'))


def recorded(migrations=OUT.parent):
    """template -> max_stack as 034 and the later update migrations leave game.item_stacks."""
    out = {}
    for path in sorted([OUT] + sorted(Path(migrations).glob('*_item_stacks_*.sql'))):
        if path.exists():
            out.update((int(t), int(m)) for t, m in re.findall(r'^\s*\((\d+), (\d+)\)', path.read_text(encoding='utf-8'), re.M))
    return out


def update(name, items=ITEMS, migrations=OUT.parent):
    """A migration upserting the stack limits that are new or changed against the recorded ones."""
    known = recorded(migrations)
    changed = [(t, m) for t, m in stacks(items) if known.get(t) != m]
    text = (f"-- Item stacks of a newer client build (generated by tools/item_stacks_sql.py update from Item.dat MaxStackCount;\n"
            f"-- do not edit by hand): {len(changed)} templates new or changed against the earlier stack migrations.\n")
    if changed:
        text += ('INSERT INTO game.item_stacks(template_id, max_stack) VALUES\n' + ',\n'.join(f'    ({t}, {m})' for t, m in changed)
                 + '\nON CONFLICT (template_id) DO UPDATE SET max_stack = EXCLUDED.max_stack;\n')
    return text, len(changed)


def build():
    lines = [HEADER]
    rows = stacks()
    for i in range(0, len(rows), 200):
        chunk = rows[i:i + 200]
        lines.append('INSERT INTO game.item_stacks(template_id, max_stack) VALUES\n' + ',\n'.join(f'    ({t}, {m})' for t, m in chunk) + ';\n')
    lines.append(FUNCTION)
    return ''.join(lines), len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('command', choices=['write', 'update'])
    parser.add_argument('migration', nargs='?', type=Path, help='update: the new migration file')
    args = parser.parse_args()
    if args.command == 'update':
        if not args.migration or args.migration.exists():
            raise SystemExit('update needs a new migration path')
        text, count = update(args.migration.name)
        args.migration.write_text(text, encoding='utf-8', newline='\n')
        print(f'{count} new or changed stack limits -> {args.migration}')
        return
    text, count = build()
    if OUT.exists() and OUT.read_text(encoding='utf-8') != text:
        raise SystemExit(f'{OUT.relative_to(ROOT)} is applied and checksummed; use update for a newer client build')
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'{count} stackable templates -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
